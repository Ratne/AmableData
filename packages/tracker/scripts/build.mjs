// Builds the three tracker variants (IIFE, minified) and writes them as string
// constants to generated/bundles.ts, which apps/edge serves from memory.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const VARIANTS = ['default', 'cookieless', 'hash'];

/** @returns {Promise<Record<string, string>>} */
export async function buildBundles() {
  const out = {};
  for (const variant of VARIANTS) {
    const result = await build({
      entryPoints: [join(root, 'src/entries', `${variant}.ts`)],
      bundle: true,
      format: 'iife',
      minify: true,
      target: ['es2019'],
      platform: 'browser',
      write: false,
      legalComments: 'none',
    });
    const file = result.outputFiles[0];
    if (file === undefined) throw new Error(`no output for ${variant}`);
    out[variant] = file.text.trim();
  }
  return out;
}

/** @param {Record<string, string>} bundles */
export function renderModule(bundles) {
  const hashes = Object.fromEntries(
    Object.entries(bundles).map(([k, v]) => [
      k,
      createHash('sha256').update(v).digest('hex').slice(0, 16),
    ]),
  );
  return [
    '// Generated by `pnpm --filter @amable/tracker build` — do not edit by hand.',
    '',
    `export const TRACKER_BUNDLES = ${JSON.stringify(bundles, null, 2)} as const;`,
    '',
    `export const TRACKER_BUNDLE_HASHES = ${JSON.stringify(hashes, null, 2)} as const;`,
    '',
    'export type TrackerVariant = keyof typeof TRACKER_BUNDLES;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bundles = await buildBundles();
  writeFileSync(join(root, 'generated/bundles.ts'), renderModule(bundles));
  for (const [k, v] of Object.entries(bundles)) console.log(`${k}: ${v.length} bytes`);
}
