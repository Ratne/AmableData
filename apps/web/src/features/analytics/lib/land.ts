function inside(lon: number, lat: number, polygon: Ring): boolean {
  let hit = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i, i += 1) {
    const [xi, yi] = polygon[i]!;
    const [xj, yj] = polygon[j]!;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export function isLand(lon: number, lat: number): boolean {
  if (!LAND.some((polygon) => inside(lon, lat, polygon))) return false;
  return !WATER.some((polygon) => inside(lon, lat, polygon));
}

/** Land dots `[lon, lat]` on an (almost) equal-area grid with `step` degrees spacing. */
function buildSphereDots(step: number): Float32Array {
  const out: number[] = [];
  for (let lat = -84; lat <= 84; lat += step) {
    const lonStep = step / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (isLand(lon, lat)) out.push(lon, lat);
    }
  }
  return new Float32Array(out);
}

/** Land dots on a regular lon/lat grid (flat equirectangular map). */
function buildGridDots(step: number): Float32Array {
  const out: number[] = [];
  for (let lat = 80; lat >= -58; lat -= step) {
    for (let lon = -180 + step / 2; lon < 180; lon += step) {
      if (isLand(lon, lat)) out.push(lon, lat);
    }
  }
  return new Float32Array(out);
}

let sphereDots: Float32Array | null = null;
let gridDots: Float32Array | null = null;

export function getSphereDots(): Float32Array {
  sphereDots ??= buildSphereDots(1.9);
  return sphereDots;
}

export function getGridDots(): Float32Array {
  gridDots ??= buildGridDots(2.6);
  return gridDots;
}
