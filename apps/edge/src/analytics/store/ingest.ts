/** Inactivity after which a cookieless/server visitor starts a new session. */
const SESSION_TIMEOUT_MS = 30 * 60_000;

export interface SessionRow {
  id: string;
  visitor_id: string;
  session_number: number;
  started_at: number;
  last_seen: number;
  entry_path: string | null;
  exit_path: string | null;
  pageviews: number;
  goals: number;
  revenue_minor: number;
}

export interface IngestOptions {
  /** Site currency: only payments in this currency count as revenue. */
  currency: string;
  /** Apply time (dedupe keys expire by it, not by the event time). */
  now?: number;
  /** Device signals module on for the site: `device` events are skipped otherwise. */
  deviceSignals?: boolean;
}

export interface IngestResult {
  ingested: number;
  duplicates: number;
  skipped: number;
  bots: number;
  /** True when the batch queued work for the core (identities, automation events, alerts). */
  pending: boolean;
  /** Events for the realtime WebSocket (identity labels included; stripped for public sockets). */
  live: RealtimeEvent[];
  /** Event ids refused by the age barrier (the caller archives them as corrections). */
  late: string[];
  /** Event ids whose apply threw (isolated from the batch; the caller archives them). */
  poison: string[];
}

/** Goals generated by this module itself never trigger page-level automation dedupe. */
const RESERVED_GOALS = new Set(['payment', 'free_trial']);

function hourBucket(ts: number): number {
  return Math.floor(ts / HOUR_MS) * HOUR_MS;
}

export function markDirty(db: SqlDb, ts: number): void {
  db.run(
    `INSERT OR IGNORE INTO rollup_dirty (grain, key) VALUES ('hour', ?)`,
    String(hourBucket(ts)),
  );
}

function upsertVisitor(db: SqlDb, e: EnrichedEvent): { session_count: number } {
  const browserHit = !e.server;
  const firstSeen = Math.min(e.firstSeen ?? e.ts, e.ts);
  const row = db.all<{ session_count: number }>(
    `INSERT INTO visitors (id, first_seen, last_seen, session_count, cookieless, first_channel, first_source,
       first_referrer_host, country, device, browser, os)
     VALUES (?, ?, ?, 0, ?, ?, ?, ?, ?, ?, ?, ?)
     ON CONFLICT (id) DO UPDATE SET
       first_seen = MIN(first_seen, excluded.first_seen),
       last_seen = MAX(last_seen, excluded.last_seen),
       first_channel = COALESCE(first_channel, excluded.first_channel),
       first_source = COALESCE(first_source, excluded.first_source),
       first_referrer_host = COALESCE(first_referrer_host, excluded.first_referrer_host),
       country = COALESCE(excluded.country, country),
       device = COALESCE(excluded.device, device),
       browser = COALESCE(excluded.browser, browser),
       os = COALESCE(excluded.os, os)
     RETURNING session_count`,
    e.vid,
    firstSeen,
    e.ts,
    e.cookieless ? 1 : 0,
    browserHit ? e.channel : null,
    browserHit ? e.source : null,
    browserHit ? e.referrerHost : null,
    e.geo.country,
    e.device,
    e.browser,
    e.os,
  )[0];
  return row ?? { session_count: 0 };
}

const SESSION_COLUMNS = `id, visitor_id, session_number, started_at, last_seen, entry_path, exit_path, pageviews, goals, revenue_minor`;

function latestSession(db: SqlDb, visitorId: string, ts: number): SessionRow | undefined {
  return first<SessionRow>(
    db,
    `SELECT ${SESSION_COLUMNS} FROM sessions
     WHERE visitor_id = ? AND last_seen >= ? AND started_at <= ?
     ORDER BY last_seen DESC LIMIT 1`,
    visitorId,
    ts - SESSION_TIMEOUT_MS,
    ts + SESSION_TIMEOUT_MS,
  );
}

function createSession(db: SqlDb, id: string, e: EnrichedEvent, sessionCount: number): SessionRow {
  const sessionNumber = e.sessionNumber ?? sessionCount + 1;
  db.run(
    `INSERT INTO sessions (id, visitor_id, session_number, started_at, last_seen, hostname, entry_path, exit_path,
       referrer, referrer_host, channel, paid, source, utm_source, utm_medium, utm_campaign, utm_term, utm_content,
       click_ids, country, region, city, latitude, longitude, device, browser, os, language,
       ad_campaign_id, ad_set_id, ad_id, ad_placement, ad_keyword, ad_network, collector)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    id,
    e.vid,
    sessionNumber,
    e.ts,
    e.ts,
    e.hostname,
    e.path,
    e.path,
    e.referrer,
    e.referrerHost,
    e.channel,
    e.paid ? 1 : 0,
    e.source,
    e.utm.source,
    e.utm.medium,
    e.utm.campaign,
    e.utm.term,
    e.utm.content,
    e.clickIds === null ? null : JSON.stringify(e.clickIds),
    e.geo.country,
    e.geo.region,
    e.geo.city,
    e.geo.latitude,
    e.geo.longitude,
    e.device,
    e.browser,
    e.os,
    e.language,
    e.ad?.campaignId ?? null,
    e.ad?.adSetId ?? null,
    e.ad?.adId ?? null,
    e.ad?.placement ?? null,
    e.ad?.keyword ?? null,
    e.ad?.network ?? null,
    e.collector ?? null,
  );
  db.run(
    `UPDATE visitors SET session_count = MAX(session_count, ?) WHERE id = ?`,
    sessionNumber,
    e.vid,
  );
  return {
    id,
    visitor_id: e.vid,
    session_number: sessionNumber,
    started_at: e.ts,
    last_seen: e.ts,
    entry_path: e.path,
    exit_path: e.path,
    pageviews: 0,
    goals: 0,
    revenue_minor: 0,
  };
}

/**
 * Finds the session an event belongs to:
 * - browser events with a cookie session id use it (created on first sight);
 * - cookieless and server events join the visitor's session active within 30 min;
 * - only pageviews (and browser goals/link clicks) may open a new session.
 */
function resolveSession(db: SqlDb, e: EnrichedEvent, sessionCount: number): SessionRow | null {
  const opens = e.server
    ? e.type === 'pageview'
    : e.type === 'pageview' || e.type === 'goal' || e.type === 'external_link';
  if (e.sid !== null) {
    const row = first<SessionRow>(
      db,
      `SELECT ${SESSION_COLUMNS} FROM sessions WHERE id = ?`,
      e.sid,
    );
    if (row !== undefined) return row;
    if (opens) return createSession(db, e.sid, e, sessionCount);
  }
  const recent = latestSession(db, e.vid, e.ts);
  if (recent !== undefined) return recent;
  if (!opens) return null;
  return createSession(db, `c${e.eid.replace(/-/g, '')}`, e, sessionCount);
}

function touchSession(
  db: SqlDb,
  s: SessionRow,
  e: EnrichedEvent,
  delta: { pageviews?: number; goals?: number; revenue?: number },
): void {
  const pv = delta.pageviews ?? 0;
  const goals = s.goals + (delta.goals ?? 0);
  const pageviews = s.pageviews + pv;
  const started = Math.min(s.started_at, e.ts);
  const last = Math.max(s.last_seen, e.ts);
  const entry = pv > 0 && (s.pageviews === 0 || e.ts < s.started_at) ? e.path : s.entry_path;
  const exit = pv > 0 && (s.pageviews === 0 || e.ts >= s.last_seen) ? e.path : s.exit_path;
  db.run(
    `UPDATE sessions SET started_at = ?, last_seen = ?, entry_path = ?, exit_path = ?, pageviews = ?, goals = ?,
       revenue_minor = revenue_minor + ?, duration_ms = ?, bounce = ? WHERE id = ?`,
    started,
    last,
    entry,
    exit,
    pageviews,
    goals,
    delta.revenue ?? 0,
    last - started,
    pageviews <= 1 && goals === 0 ? 1 : 0,
    s.id,
  );
  if (started !== s.started_at) markDirty(db, s.started_at);
  markDirty(db, started);
  // The row is written with absolute values: keep it current for a second touch of the same event.
  Object.assign(s, {
    started_at: started,
    last_seen: last,
    entry_path: entry,
    exit_path: exit,
    pageviews,
    goals,
    revenue_minor: s.revenue_minor + (delta.revenue ?? 0),
  });
  // Ad platform cookies often appear after the landing (their pixel loads later).
  const cookies = platformCookies(e.clickIds);
  if (cookies !== null) {
    db.run(
      `UPDATE sessions SET click_ids = json_patch(?1, COALESCE(click_ids, '{}'))
       WHERE id = ?2 AND (click_ids IS NULL OR json_patch(?1, click_ids) <> click_ids)`,
      cookies,
      s.id,
    );
  }
}

const PLATFORM_COOKIE_KEYS = ['fbp', 'fbc', 'ttp'] as const;

function platformCookies(clickIds: Record<string, string> | null): string | null {
  if (clickIds === null) return null;
  const out: Record<string, string> = {};
  for (const k of PLATFORM_COOKIE_KEYS) if (clickIds[k] !== undefined) out[k] = clickIds[k];
  return Object.keys(out).length > 0 ? JSON.stringify(out) : null;
}

function ingestPayment(
  db: SqlDb,
  e: EnrichedEvent,
  session: SessionRow | null,
  vid: string | null,
  opts: IngestOptions,
  out: BatchState,
): void {
  const p = e.payment;
  if (p === null) return;
  const counts = p.currency === opts.currency;
  const source = e.server ? 'server' : 'tracker';
  const inserted = db.all<{ id: number }>(
    `INSERT INTO payments (transaction_id, visitor_id, session_id, ts, amount_minor, currency, email, customer_id,
       renewal, refunded, free_trial, refunded_minor, source)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
     ON CONFLICT (transaction_id) DO NOTHING RETURNING id`,
    p.transactionId,
    vid,
    session?.id ?? null,
    e.ts,
    p.amountMinor,
    p.currency,
    p.email,
    p.customerId,
    p.renewal ? 1 : 0,
    p.refunded ? 1 : 0,
    p.freeTrial ? 1 : 0,
    p.refunded ? p.amountMinor : 0,
    source,
  );
  if (inserted.length > 0) {
    const goalName = p.freeTrial ? 'free_trial' : 'payment';
    if (vid !== null) {
      db.run(
        `INSERT INTO goals (session_id, visitor_id, ts, name, path, params) VALUES (?, ?, ?, ?, ?, ?)`,
        session?.id ?? null,
        vid,
        e.ts,
        goalName,
        e.path,
        JSON.stringify({ transaction_id: p.transactionId }),
      );
      afterGoal(db, out, { ...e, vid, name: goalName }, session, null);
    }
    if (session !== null) {
      touchSession(db, session, e, {
        goals: vid === null ? 0 : 1,
        revenue: counts && !p.refunded ? p.amountMinor : 0,
      });
    }
    out.live.push(liveEvent(db, { ...e, vid: vid ?? '' }, session));
    return;
  }
  // Known transaction: a later full refund removes what is left of it (once).
  if (!p.refunded) return;
  refundPayment(db, p.transactionId, null, opts.currency);
}

/**
 * Applies a refund of `amount` (null = everything left) to a payment: grows
 * `refunded_minor`, flags the payment fully refunded at zero and takes the
 * amount off the revenue of its session. Returns the amount actually refunded.
 */
export function refundPayment(
  db: SqlDb,
  transactionId: string,
  amount: number | null,
  currency: string,
): number {
  const prev = first<{
    refunded: number;
    refunded_minor: number;
    session_id: string | null;
    amount_minor: number;
    currency: string;
    ts: number;
  }>(
    db,
    `SELECT refunded, refunded_minor, session_id, amount_minor, currency, ts FROM payments WHERE transaction_id = ?`,
    transactionId,
  );
  if (prev === undefined || prev.refunded === 1) return 0;
  const left = prev.amount_minor - prev.refunded_minor;
  const take = Math.max(0, Math.min(left, amount ?? left));
  if (take === 0) return 0;
  const refundedMinor = prev.refunded_minor + take;
  db.run(
    `UPDATE payments SET refunded_minor = ?, refunded = ? WHERE transaction_id = ?`,
    refundedMinor,
    refundedMinor >= prev.amount_minor ? 1 : 0,
    transactionId,
  );
  if (prev.session_id !== null && prev.currency === currency) {
    db.run(
      `UPDATE sessions SET revenue_minor = revenue_minor - ? WHERE id = ?`,
      take,
      prev.session_id,
    );
  }
  markDirty(db, prev.ts);
  return take;
}

/** Mutable state collected while a batch is applied. */
export interface BatchState {
  pending: boolean;
  live: RealtimeEvent[];
  /** `session:path` pairs already queued for automations in this batch. */
  pagesQueued: Set<string>;
  /** Enabled conversion rules, read once per batch. */
  rules?: Rule[];
}

function rulesOf(db: SqlDb, out: BatchState): Rule[] {
  out.rules ??= activeRules(db);
  return out.rules;
}

/**
 * Pageview rules matching a stored pageview: each new conversion also records
 * a goal named after the rule (`params.rule`), so it shows in realtime,
 * journeys, funnels, alerts and automations. Those goals never trigger rules.
 */
function convertPageview(
  db: SqlDb,
  out: BatchState,
  opts: IngestOptions,
  e: EnrichedEvent,
  session: SessionRow,
  pageviewId: number,
): void {
  const path = e.path;
  if (path === null) return;
  for (const rule of rulesOf(db, out)) {
    if (rule.trigger !== 'pageview' || !pageMatches(rule, e.hostname, path)) continue;
    const match = { visitorId: e.vid, sessionId: session.id, ts: e.ts, ref: `pv:${pageviewId}`, trigger: path };
    if (!recordRuleConversion(db, rule, match, opts.currency, opts.now ?? Date.now())) continue;
    const data = { rule: rule.id };
    db.run(
      `INSERT INTO goals (session_id, visitor_id, ts, name, path, params) VALUES (?, ?, ?, ?, ?, ?)`,
      session.id,
      e.vid,
      e.ts,
      rule.key,
      path,
      JSON.stringify(data),
    );
    touchSession(db, session, e, { goals: 1 });
    const goal: EnrichedEvent = { ...e, type: 'goal', name: rule.key, data };
    afterGoal(db, out, goal, session, null);
    out.live.push(liveEvent(db, goal, session));
  }
}

/** Goal rules matching a stored goal (browser, server or CRM). */
export function convertGoal(
  db: SqlDb,
  out: BatchState,
  currency: string,
  now: number,
  g: { visitorId: string; sessionId: string | null; ts: number; goalId: number; name: string },
): void {
  for (const rule of rulesOf(db, out)) {
    if (rule.trigger !== 'goal' || rule.value !== g.name) continue;
    recordRuleConversion(
      db,
      rule,
      { visitorId: g.visitorId, sessionId: g.sessionId, ts: g.ts, ref: `g:${g.goalId}`, trigger: g.name },
      currency,
      now,
    );
  }
}

export function newBatchState(): BatchState {
  return { pending: false, live: [], pagesQueued: new Set() };
}

function contactOf(db: SqlDb, visitorId: string): string | null {
  return (
    first<{ contact_id: string | null }>(
      db,
      `SELECT contact_id FROM visitors WHERE id = ?`,
      visitorId,
    )?.contact_id ?? null
  );
}

/**
 * After a goal is stored: queue it for the automation engine when the visitor
 * is a known contact, and for every enabled alert watching that goal.
 */
export function afterGoal(
  db: SqlDb,
  out: BatchState,
  e: Pick<EnrichedEvent, 'vid' | 'ts' | 'name' | 'path' | 'hostname' | 'data'>,
  session: Pick<SessionRow, 'id'> | null,
  contactId: string | null,
  queueAutomation = true,
): void {
  if (e.name === null) return;
  const contact = queueAutomation ? (contactId ?? contactOf(db, e.vid)) : null;
  if (contact !== null) {
    db.run(
      `INSERT INTO automation_queue (kind, visitor_id, contact_id, session_id, name, hostname, path, params, ts)
       VALUES ('goal', ?, ?, ?, ?, ?, ?, ?, ?)`,
      e.vid,
      contact,
      session?.id ?? null,
      e.name,
      e.hostname,
      e.path,
      e.data === null ? null : JSON.stringify(e.data),
      e.ts,
    );
    out.pending = true;
  }
  const alerts = db.all<{ id: string }>(
    `SELECT id FROM alerts WHERE enabled = 1 AND goal = ?`,
    e.name,
  );
  for (const alert of alerts) {
    db.run(
      `INSERT INTO alert_queue (alert_id, goal, visitor_id, test, ts) VALUES (?, ?, ?, 0, ?)`,
      alert.id,
      e.name,
      e.vid,
      e.ts,
    );
    out.pending = true;
  }
}

function afterPageview(db: SqlDb, out: BatchState, e: EnrichedEvent, session: SessionRow): void {
  if (e.path === null) return;
  const contact = contactOf(db, e.vid);
  if (contact === null) return;
  const key = `${session.id}:${e.path}`;
  if (out.pagesQueued.has(key)) return;
  // One automation event per page and session: reloads and back/forward stay quiet.
  const seen = first<{ n: number }>(
    db,
    `SELECT COUNT(*) AS n FROM pageviews WHERE session_id = ? AND path = ?`,
    session.id,
    e.path,
  );
  out.pagesQueued.add(key);
  if ((seen?.n ?? 0) > 1) return;
  db.run(
    `INSERT INTO automation_queue (kind, visitor_id, contact_id, session_id, name, hostname, path, params, ts)
     VALUES ('pageview', ?, ?, ?, NULL, ?, ?, ?, ?)`,
    e.vid,
    contact,
    session.id,
    e.hostname,
    e.path,
    e.url === null ? null : JSON.stringify({ url: e.url }),
    e.ts,
  );
  out.pending = true;
}

/** Display label of an identified visitor (sites hold no clear names or emails: the core labels contacts). */
function labelOf(db: SqlDb, visitorId: string): string | null {
  return (
    first<{ name: string | null }>(db, `SELECT name FROM visitors WHERE id = ?`, visitorId)?.name ??
    null
  );
}

function liveEvent(db: SqlDb, e: EnrichedEvent, session: SessionRow | null): RealtimeEvent {
  const host = typeof e.data?.['host'] === 'string' ? e.data['host'] : null;
  return {
    type: e.type as RealtimeEvent['type'],
    ts: new Date(e.ts).toISOString(),
    visitor_id: e.vid,
    path: e.path,
    name: e.type === 'external_link' ? host : e.type === 'goal' ? e.name : null,
    country: e.geo.country,
    city: e.geo.city,
    latitude: e.geo.latitude,
    longitude: e.geo.longitude,
    channel: session === null ? null : e.channel,
    device: e.device,
    amount_minor: e.payment === null ? null : e.payment.amountMinor,
    currency: e.payment === null ? null : e.payment.currency,
    label: e.vid === '' ? null : labelOf(db, e.vid),
  };
}

function ingestOne(
  db: SqlDb,
  e: EnrichedEvent,
  opts: IngestOptions,
  out: BatchState,
): 'ok' | 'duplicate' | 'skipped' {
  if (!claimEvent(db, e.eid, opts.now ?? Date.now())) return 'duplicate';
  if (e.type === 'device') {
    // Off (or turned off while the event was on its way: edge cache, queue, replay): nothing is kept.
    if (opts.deviceSignals !== true) return 'skipped';
    if (e.deviceSighting == null || e.vid === '') return 'skipped';
    const known = first<{ n: number }>(db, `SELECT 1 AS n FROM visitors WHERE id = ?`, e.vid);
    if (known === undefined) return 'skipped';
    recordDevice(
      db,
      e.vid,
      { ...e.deviceSighting, browser: e.browser, os: e.os },
      opts.now ?? Date.now(),
    );
    return 'ok';
  }
  const signals = signalsFromEvent(e);
  const keys = signals === null ? [] : identityKeyRefs(signals);
  // GDPR: events carrying a blacklisted email/phone are dropped.
  if (isBlacklisted(db, keys)) return 'skipped';
  markDirty(db, e.ts);

  let vid: string | null = e.vid === '' ? null : e.vid;
  if (vid === null && e.payment?.email) {
    vid =
      first<{ id: string }>(
        db,
        `SELECT id FROM visitors WHERE email = ? ORDER BY last_seen DESC LIMIT 1`,
        e.payment.email,
      )?.id ?? null;
  }
  if (vid === null) vid = visitorForKeys(db, keys);
  if (vid === null) {
    if (e.type !== 'payment') return 'skipped';
    ingestPayment(db, e, null, null, opts, out);
    return 'ok';
  }
  const event = vid === e.vid ? e : { ...e, vid };
  const isNew =
    event.ipUa != null &&
    first<{ n: number }>(db, `SELECT 1 AS n FROM visitors WHERE id = ?`, vid) === undefined;
  const visitor = upsertVisitor(db, event);
  const session = resolveSession(db, event, visitor.session_count);
  if (!event.server && event.url !== null) {
    db.run(
      `UPDATE site_config SET last_event_at = ?, last_event_url = ? WHERE id = 1`,
      event.ts,
      event.url,
    );
  }
  if (event.contactToken) {
    db.run(
      `INSERT INTO identity_queue (visitor_id, kind, value, ts) VALUES (?, 'contact_token', ?, ?)`,
      vid,
      event.contactToken,
      event.ts,
    );
    out.pending = true;
  }
  if (signals !== null)
    recordIdentity(db, vid, { ...signals, sessionId: session?.id ?? null }, event.ts, event.ts);
  if (event.ipUa != null) recordIpUa(db, vid, event.ipUa, isNew, opts.now ?? Date.now());

  switch (event.type) {
    case 'pageview':
      if (session === null || event.path === null) return 'skipped';
      {
        const [pv] = db.all<{ id: number }>(
          `INSERT INTO pageviews (session_id, visitor_id, ts, hostname, path) VALUES (?, ?, ?, ?, ?) RETURNING id`,
          session.id,
          vid,
          event.ts,
          event.hostname ?? '',
          event.path,
        );
        touchSession(db, session, event, { pageviews: 1 });
        afterPageview(db, out, event, session);
        out.live.push(liveEvent(db, event, session));
        if (pv !== undefined) convertPageview(db, out, opts, event, session, pv.id);
      }
      break;
    case 'goal':
      if (event.name === null) return 'skipped';
      {
        const [goal] = db.all<{ id: number }>(
          `INSERT INTO goals (session_id, visitor_id, ts, name, path, params) VALUES (?, ?, ?, ?, ?, ?) RETURNING id`,
          session?.id ?? null,
          vid,
          event.ts,
          event.name,
          event.path,
          event.data === null ? null : JSON.stringify(event.data),
        );
        if (session !== null) touchSession(db, session, event, { goals: 1 });
        if (!RESERVED_GOALS.has(event.name)) afterGoal(db, out, event, session, null);
        out.live.push(liveEvent(db, event, session));
        if (goal !== undefined) {
          convertGoal(db, out, opts.currency, opts.now ?? Date.now(), {
            visitorId: vid,
            sessionId: session?.id ?? null,
            ts: event.ts,
            goalId: goal.id,
            name: event.name,
          });
        }
      }
      break;
    case 'external_link': {
      const url = typeof event.data?.['url'] === 'string' ? event.data['url'] : null;
      const host = typeof event.data?.['host'] === 'string' ? event.data['host'] : null;
      if (url === null || host === null) return 'skipped';
      db.run(
        `INSERT INTO exit_links (session_id, visitor_id, ts, url, host, path) VALUES (?, ?, ?, ?, ?, ?)`,
        session?.id ?? null,
        vid,
        event.ts,
        url,
        host,
        event.path,
      );
      if (session !== null) touchSession(db, session, event, {});
      out.live.push(liveEvent(db, event, session));
      break;
    }
    case 'identify': {
      const id = event.identity;
      if (id === null) return 'skipped';
      const prev = first<{ traits: string | null }>(
        db,
        `SELECT traits FROM visitors WHERE id = ?`,
        vid,
      );
      const traits =
        id.traits === null
          ? (prev?.traits ?? null)
          : JSON.stringify({
              ...(prev?.traits ? (JSON.parse(prev.traits) as object) : {}),
              ...id.traits,
            });
      // Contact data reaches the registry, not the site: only hashes are kept here.
      const emailHash = id.email === null ? null : landingEmailHash(id.email);
      const rawPhone = id.traits?.['phone'];
      const phoneHash = typeof rawPhone === 'string' ? phoneKeyHash(rawPhone) : null;
      db.run(
        `UPDATE visitors SET user_id = COALESCE(?, user_id), email = COALESCE(?, email), traits = ? WHERE id = ?`,
        id.userId,
        emailHash,
        traits,
        vid,
      );
      for (const [kind, value] of [
        ['email_hash', emailHash],
        ['phone_hash', phoneHash],
      ] as const) {
        if (value === null) continue;
        db.run(
          `INSERT INTO identity_queue (visitor_id, kind, value, ts) VALUES (?, ?, ?, ?)`,
          vid,
          kind,
          value,
          event.ts,
        );
        out.pending = true;
      }
      out.live.push(liveEvent(db, event, session));
      break;
    }
    case 'payment':
      ingestPayment(db, event, session, vid, opts, out);
      break;
  }
  return 'ok';
}

function utcDay(ts: number): string {
  return new Date(ts).toISOString().slice(0, 10);
}

/** Applies a batch of enriched events and bot hits in one transaction (idempotent per event id). */
export function ingestBatch(
  db: SqlDb,
  events: readonly EnrichedEvent[],
  bots: readonly BotHit[],
  opts: IngestOptions,
): IngestResult {
  return db.transaction(() => {
    const out = newBatchState();
    const result: IngestResult = {
      ingested: 0,
      duplicates: 0,
      skipped: 0,
      bots: 0,
      pending: false,
      live: out.live,
      late: [],
      poison: [],
    };
    for (const e of [...events].sort((a, b) => a.ts - b.ts)) {
      const r = ingestOne(db, e, opts, out);
      if (r === 'ok') result.ingested += 1;
      else if (r === 'duplicate') result.duplicates += 1;
      else result.skipped += 1;
    }
    for (const hit of bots) {
      if (hit.id !== undefined && !claimEvent(db, `bot:${hit.id}`, opts.now ?? Date.now())) {
        result.duplicates += 1;
        continue;
      }
      const verified = hit.verification === 'verified' ? 1 : 0;
      const spoofed = hit.verification === 'spoofed' ? 1 : 0;
      db.run(
        `INSERT INTO bot_hits (day, category, provider, bot, path, hits, verified_hits, spoofed_hits)
         VALUES (?, ?, ?, ?, ?, 1, ?, ?)
         ON CONFLICT (day, category, provider, bot, path) DO UPDATE SET hits = hits + 1,
           verified_hits = verified_hits + excluded.verified_hits, spoofed_hits = spoofed_hits + excluded.spoofed_hits`,
        utcDay(hit.ts),
        hit.category,
        hit.provider,
        hit.name,
        hit.path.slice(0, 512),
        verified,
        spoofed,
      );
      result.bots += 1;
    }
    result.pending = out.pending;
    return result;
  });
}
