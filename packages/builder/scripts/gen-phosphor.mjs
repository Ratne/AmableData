// Regenerates src/phosphor/* from the @phosphor-icons/core assets (MIT).
// Usage: node scripts/gen-phosphor.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = join(dirname(require.resolve('@phosphor-icons/core')), '..');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const { icons } = await import(join(pkgDir, 'dist/index.mjs'));
const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'phosphor');
mkdirSync(outDir, { recursive: true });

const WEIGHTS = ['regular', 'thin', 'light', 'bold', 'fill', 'duotone'];
const HEADER = `// Generated by scripts/gen-phosphor.mjs from @phosphor-icons/core ${version} (MIT). Do not edit.\n`;
const ROOT = /^<svg[^>]*>|<\/svg>\s*$/g;

for (const weight of WEIGHTS) {
  const dir = join(pkgDir, 'assets', weight);
  const suffix = weight === 'regular' ? '.svg' : `-${weight}.svg`;
  const entries = readdirSync(dir)
    .filter((f) => f.endsWith(suffix))
    .sort()
    .map((f) => [
      f.slice(0, -suffix.length),
      readFileSync(join(dir, f), 'utf8').trim().replace(ROOT, ''),
    ]);
  const body = entries
    .map(([name, inner]) => `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`)
    .join('\n');
  writeFileSync(
    join(outDir, `${weight}.ts`),
    `${HEADER}const GLYPHS: Record<string, string> = {\n${body}\n};\nexport default GLYPHS;\n`,
  );
}

const rows = icons
  .map((i) => {
    const terms = [...new Set([...i.categories, ...i.tags].filter((t) => !t.startsWith('*')))].join(
      ' ',
    );
    return `  [${JSON.stringify(i.name)}, ${JSON.stringify(terms)}],`;
  })
  .sort()
  .join('\n');
writeFileSync(
  join(outDir, 'catalog.ts'),
  `${HEADER}/** [glyph name, search terms (categories + tags)] */\nexport const PHOSPHOR_CATALOG: ReadonlyArray<readonly [string, string]> = [\n${rows}\n];\n`,
);
console.log(`phosphor ${version}: ${icons.length} glyphs x ${WEIGHTS.length} weights`);
