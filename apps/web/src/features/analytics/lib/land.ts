/*
 * Hand-drawn coarse land outlines `[lon, lat]` (a few hundred vertices for the
 * whole world), good enough for a dotted globe and a flat dot map. `WATER`
 * polygons are carved out of the land (inland seas, bays).
 */

type Ring = readonly (readonly [number, number])[];

function ring(flat: readonly number[]): Ring {
  const points: [number, number][] = [];
  for (let i = 0; i + 1 < flat.length; i += 2) points.push([flat[i]!, flat[i + 1]!]);
  return points;
}

