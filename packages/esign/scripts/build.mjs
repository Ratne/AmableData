// Builds the signing page app (preact, IIFE, minified) and writes it as a
// string constant to generated/bundle.ts, which apps/edge serves from memory
// at /sign.js.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** @returns {Promise<string>} */
export async function buildBundle() {
  const result = await build({
    entryPoints: [join(root, 'src/widget/main.tsx')],
    bundle: true,
    format: 'iife',
    minify: true,
    target: ['es2019'],
    platform: 'browser',
    jsx: 'automatic',
    jsxImportSource: 'preact',
    define: { 'process.env.NODE_ENV': '"production"' },
    write: false,
    legalComments: 'none',
  });
  const file = result.outputFiles[0];
  if (file === undefined) throw new Error('no signing app output');
  return file.text.trim();
}

/** @param {string} bundle */
export function renderModule(bundle) {
  const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 16);
  return [
    '// Generated by `pnpm --filter @amable/esign build` — do not edit by hand.',
    '',
    `export const ESIGN_APP_BUNDLE = ${JSON.stringify(bundle)};`,
    '',
    `export const ESIGN_APP_BUNDLE_HASH = ${JSON.stringify(hash)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bundle = await buildBundle();
  writeFileSync(join(root, 'generated/bundle.ts'), renderModule(bundle));
  console.log(`signing app: ${bundle.length} bytes`);
}
