import type { GoalTrigger } from '@amable/api-types';

/**
 * Event as seen by the engine: outbox events (CRM, e-commerce), events pushed
 * by other modules and synthetic engine events (API goals, date anniversaries).
 */
export interface EngineEvent {
  readonly id: string;
  readonly type: string;
  readonly occurredAt: string;
  readonly payload: Readonly<Record<string, unknown>>;
}

function str(payload: Readonly<Record<string, unknown>>, key: string): string | null {
  const value = payload[key];
  return typeof value === 'string' ? value : null;
}

function num(payload: Readonly<Record<string, unknown>>, key: string): number | null {
  const value = payload[key];
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function strings(payload: Readonly<Record<string, unknown>>, key: string): string[] {
  const value = payload[key];
  return Array.isArray(value) ? value.filter((v): v is string => typeof v === 'string') : [];
}

export function eventContactId(event: EngineEvent): string | null {
  return str(event.payload, 'contactId');
}

const anyOf = (wanted: readonly string[] | undefined, actual: string | null): boolean =>
  wanted === undefined || wanted.length === 0 || (actual !== null && wanted.includes(actual));

function emailSourceMatches(
  ref: Extract<GoalTrigger, { type: 'email_opened' }>['email'],
  payload: Readonly<Record<string, unknown>>,
): boolean {
  if (ref === undefined) return true;
  const raw = payload['source'];
  const source = typeof raw === 'object' && raw !== null ? (raw as Record<string, unknown>) : {};
  const field = (key: string): unknown => source[key];
  if (ref.broadcast_id !== undefined && field('broadcastId') !== ref.broadcast_id) return false;
  if (ref.automation_id !== undefined && field('automationId') !== ref.automation_id) return false;
  if (ref.node_id !== undefined && field('nodeId') !== ref.node_id) return false;
  if (ref.step_id !== undefined && field('stepId') !== ref.step_id) return false;
  return true;
}

/** True when `event` (already of a type the trigger listens to) satisfies the trigger. */
export function triggerMatches(trigger: GoalTrigger, event: EngineEvent): boolean {
  const p = event.payload;
  switch (trigger.type) {
    case 'tag_applied':
    case 'tag_removed':
      return trigger.tag_ids.includes(str(p, 'tagId') ?? '');
    case 'contact_created':
      return true;
    case 'form_submitted':
      return anyOf(trigger.form_ids, str(p, 'formId'));
    case 'product_purchased': {
      const wanted = trigger.product_ids ?? [];
      return wanted.length === 0 || strings(p, 'productIds').some((id) => wanted.includes(id));
    }
    case 'order_paid': {
      const total = num(p, 'amountMinor') ?? num(p, 'totalMinor') ?? 0;
      return total >= (trigger.min_total_minor ?? 0);
    }
    case 'email_opened':
      return emailSourceMatches(trigger.email, p);
    case 'email_clicked':
      return (
        emailSourceMatches(trigger.email, p) &&
        (trigger.url_contains === undefined || (str(p, 'url') ?? '').includes(trigger.url_contains))
      );
    case 'lead_score': {
      const from = num(p, 'from');
      const to = num(p, 'to');
      if (from === null || to === null) return false;
      return trigger.direction === 'drops_below'
        ? from >= trigger.threshold && to < trigger.threshold
        : from < trigger.threshold && to >= trigger.threshold;
    }
    case 'api':
      return str(p, 'callName') === trigger.call_name;
    case 'web_goal':
      return (
        str(p, 'goalName') === trigger.goal_name &&
        (trigger.site_id === undefined || str(p, 'siteId') === trigger.site_id)
      );
    case 'appointment_booked':
      if (event.type === 'appointment.created') {
        return trigger.include_crm_appointments === true && str(p, 'source') !== 'booking';
      }
      return anyOf(trigger.event_type_ids, str(p, 'eventTypeId'));
    case 'opportunity_stage_changed':
      return (
        (trigger.pipeline_id === undefined || str(p, 'pipelineId') === trigger.pipeline_id) &&
        anyOf(trigger.to_stage_ids, str(p, 'toStageId')) &&
        anyOf(trigger.from_stage_ids, str(p, 'fromStageId'))
      );
    case 'date_anniversary':
      // Synthetic event generated by the daily scan for this very goal.
      return true;
    case 'app_event':
      return str(p, 'appId') === trigger.app_id && str(p, 'key') === trigger.key;
    case 'document_completed':
    case 'document_declined':
      return anyOf(trigger.template_ids, str(p, 'templateId'));
  }
}
