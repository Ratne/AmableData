#!/usr/bin/env node
/**
 * Local dev: one command for the whole installation.
 *
 *   node scripts/dev.mjs [--port 8787] [--edge-port 8788] [--ip localhost]
 *                        [--persist-to apps/core/.wrangler/state] [--skip-build]
 *
 * 1. Builds the tracker bundles and the SPA (skip with --skip-build).
 * 2. Runs core + edge in ONE wrangler session (`-c core -c edge`): the core's
 *    cross-script AnalyticsDO binding (`script_name: amable-edge`) and the edge's
 *    CORE service binding only resolve inside a single session.
 * 3. Only the first config gets an HTTP port, so the edge public endpoints (tracker
 *    script, /e ingest, hosted forms/booking, /r /o /unsub, landing pages) are
 *    served on the edge port by a small proxy: it forwards to the core port with
 *    the `x-amable-dev-edge` header, and the core (ENVIRONMENT=dev only) hands
 *    those requests to the edge worker through the EDGE_DEV service binding added
 *    to a generated config (apps/core/wrangler.dev.jsonc, git-ignored).
 *
 * EDGE_ORIGIN (core: snippets, hosted links) and CORE_ORIGIN (edge) are set to
 * the two local origins so tracker snippets and email links work end to end.
 */
import { spawn, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = path.join(repoRoot, 'apps/core');
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : fallback;
};

const ip = opt('ip', 'localhost');
const port = Number(opt('port', '8787'));
const edgePort = Number(opt('edge-port', '8788'));
const persistTo = path.resolve(repoRoot, opt('persist-to', 'apps/core/.wrangler/state'));
const coreOrigin = `http://${ip}:${port}`;
const edgeOrigin = `http://${ip}:${edgePort}`;
export const DEV_EDGE_HEADER = 'x-amable-dev-edge';

/** Strips comments and trailing commas from a JSONC document (strings are preserved). */
export function parseJsonc(text) {
  let out = '';
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    if (ch === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === '\\' ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
    } else if (ch === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i += 1;
    } else if (ch === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2);
      i = end < 0 ? text.length : end + 2;
    } else {
      out += ch;
      i += 1;
    }
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, '$1'));
}

/** Core config + the dev-only EDGE_DEV service binding to the edge worker's fetch. */
export function devCoreConfig(config, origins) {
  const services = (config.services ?? []).filter((s) => s.binding !== 'EDGE_DEV');
  return {
    ...config,
    services: [...services, { binding: 'EDGE_DEV', service: 'amable-edge' }],
    vars: { ...config.vars, EDGE_ORIGIN: origins.edge },
  };
}

/** Edge config pointing back at the local core origin. */
export function devEdgeConfig(config, origins) {
  return { ...config, vars: { ...config.vars, CORE_ORIGIN: origins.core } };
}

/**
 * `--var` only reaches the first worker of a multi-config session, so both configs
 * are rewritten next to the originals (relative paths and .dev.vars keep working).
 */
function writeDevConfig(dir, transform) {
  const config = transform(parseJsonc(readFileSync(path.join(dir, 'wrangler.jsonc'), 'utf8')), {
    core: coreOrigin,
    edge: edgeOrigin,
  });
  writeFileSync(
    path.join(dir, 'wrangler.dev.jsonc'),
    `// Generated by scripts/dev.mjs from wrangler.jsonc — do not edit, not committed.\n${JSON.stringify(config, null, 2)}\n`,
  );
}

function run(command, commandArgs) {
  const result = spawnSync(command, commandArgs, { cwd: repoRoot, stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function startEdgeProxy() {
  const server = http.createServer((req, res) => {
    const upstream = http.request(
      {
        host: ip === 'localhost' ? '127.0.0.1' : ip,
        port,
        method: req.method,
        path: req.url,
        headers: { ...req.headers, [DEV_EDGE_HEADER]: req.headers.host ?? `${ip}:${edgePort}` },
      },
      (upstreamRes) => {
        res.writeHead(upstreamRes.statusCode ?? 502, upstreamRes.headers);
        upstreamRes.pipe(res);
      },
    );
    upstream.on('error', (error) => {
      if (!res.headersSent) res.writeHead(502, { 'content-type': 'text/plain' });
      res.end(`edge proxy: core worker not reachable on ${coreOrigin} (${error.message})`);
    });
    req.pipe(upstream);
  });
  server.listen(edgePort, ip === 'localhost' ? '127.0.0.1' : ip);
  return server;
}

const isMain = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (!args.includes('--skip-build')) {
    run('pnpm', ['--filter', '@amable/tracker', 'build']);
    run('pnpm', ['run', 'build:web']);
  }

  writeDevConfig(coreDir, devCoreConfig);
  writeDevConfig(path.join(repoRoot, 'apps/edge'), devEdgeConfig);

  const wrangler = spawn(
    'npx',
    [
      'wrangler', 'dev',
      '-c', 'wrangler.dev.jsonc',
      '-c', '../edge/wrangler.dev.jsonc',
      '--port', String(port),
      '--ip', ip,
      '--persist-to', persistTo,
      '--show-interactive-dev-session=false',
    ],
    { cwd: coreDir, stdio: 'inherit', env: process.env },
  );
  const proxy = startEdgeProxy();
  console.log(`\n  core  ${coreOrigin}  (app + API)\n  edge  ${edgeOrigin}  (tracker, /e ingest, hosted pages)\n`);

  const stop = () => {
    proxy.close();
    wrangler.kill('SIGINT');
  };
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
  wrangler.on('exit', (code) => {
    proxy.close();
    process.exit(code ?? 0);
  });
}
